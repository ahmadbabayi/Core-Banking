    ON product(currency_id);


CREATE INDEX idx_ledger_account_parent_id
    ON ledger_account(parent_id);


CREATE INDEX idx_ledger_account_currency_id
    ON ledger_account(currency_id);


CREATE INDEX idx_account_account_type_id
    ON account(account_type_id);


CREATE INDEX idx_account_product_id
    ON account(product_id);


CREATE INDEX idx_account_currency_id
    ON account(currency_id);


CREATE INDEX idx_account_opening_branch_id
    ON account(opening_branch_id);


CREATE INDEX idx_account_ledger_account_id
    ON account(ledger_account_id);


CREATE INDEX idx_account_status
    ON account(status);
