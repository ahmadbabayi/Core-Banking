-- ============================================================
-- 6. ACCOUNT MANDATE PARTY
-- ============================================================

CREATE TABLE account_mandate_party (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    mandate_id BIGINT NOT NULL,

    customer_id BIGINT NOT NULL,

    role VARCHAR(30) NOT NULL DEFAULT 'SIGNATORY',

    valid_from DATE NOT NULL,

    valid_to DATE,

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_account_mandate_party_mandate
        FOREIGN KEY (mandate_id)
        REFERENCES account_mandate(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_account_mandate_party_customer
        FOREIGN KEY (customer_id)
        REFERENCES customer(id),

    CONSTRAINT ck_account_mandate_party_role
        CHECK (
            role IN (
                'SIGNATORY'
            )
        ),

    CONSTRAINT ck_account_mandate_party_dates
        CHECK (
            valid_to IS NULL
            OR valid_to >= valid_from
        ),

    CONSTRAINT ck_account_mandate_party_status
        CHECK (
            status IN (
                'ACTIVE',
                'INACTIVE'
            )
        )
);


-- ============================================================
-- 7. ACCOUNT MANDATE RULE
-- ============================================================

CREATE TABLE account_mandate_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    mandate_id BIGINT NOT NULL,

    operation_type VARCHAR(30) NOT NULL,

    required_signatures SMALLINT NOT NULL,

    valid_from DATE NOT NULL,

    valid_to DATE,

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_account_mandate_rule_mandate
        FOREIGN KEY (mandate_id)
        REFERENCES account_mandate(id)
        ON DELETE CASCADE,

    CONSTRAINT ck_account_mandate_rule_operation
        CHECK (
            operation_type IN (
                'WITHDRAWAL',
                'TRANSFER',
                'PAYMENT',
                'CLOSE_ACCOUNT'
            )
        ),

    CONSTRAINT ck_account_mandate_rule_required_signatures
        CHECK (
            required_signatures >= 1
        ),

    CONSTRAINT ck_account_mandate_rule_dates
        CHECK (
            valid_to IS NULL
            OR valid_to >= valid_from
        ),

    CONSTRAINT ck_account_mandate_rule_status
        CHECK (
            status IN (
                'ACTIVE',
                'INACTIVE'
            )
        )
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_account_owner_customer_id
    ON account_owner(customer_id);

CREATE UNIQUE INDEX uq_account_owner_active
    ON account_owner(account_id, customer_id)
    WHERE status = 'ACTIVE';


CREATE INDEX idx_account_authorization_customer_id
    ON account_authorization(customer_id);

CREATE UNIQUE INDEX uq_account_authorization_active
    ON account_authorization(
        account_id,
        customer_id,
        authorization_type
    )
    WHERE status = 'ACTIVE';


CREATE INDEX idx_board_member_legal_entity
    ON legal_entity_board_member(legal_entity_customer_id);

CREATE INDEX idx_board_member_customer
    ON legal_entity_board_member(customer_id);

CREATE INDEX idx_board_member_status
    ON legal_entity_board_member(status);


CREATE INDEX idx_shareholder_legal_entity
    ON legal_entity_shareholder(legal_entity_customer_id);

CREATE INDEX idx_shareholder_customer
    ON legal_entity_shareholder(shareholder_customer_id);

CREATE INDEX idx_shareholder_status
    ON legal_entity_shareholder(status);


CREATE INDEX idx_account_mandate_account_id
    ON account_mandate(account_id);

CREATE INDEX idx_account_mandate_status
    ON account_mandate(status);


CREATE INDEX idx_account_mandate_party_customer_id
    ON account_mandate_party(customer_id);

CREATE UNIQUE INDEX uq_account_mandate_party_active
    ON account_mandate_party(mandate_id, customer_id)
    WHERE status = 'ACTIVE';

CREATE INDEX idx_account_mandate_party_status
    ON account_mandate_party(status);


CREATE UNIQUE INDEX uq_account_mandate_rule_active
    ON account_mandate_rule(mandate_id, operation_type)
    WHERE status = 'ACTIVE';

CREATE INDEX idx_account_mandate_rule_status
    ON account_mandate_rule(status);
