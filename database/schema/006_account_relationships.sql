-- ============================================================
-- 1. ACCOUNT OWNER
-- ============================================================

CREATE TABLE account_owner (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    account_id BIGINT NOT NULL,

    customer_id BIGINT NOT NULL,

    valid_from DATE NOT NULL,

    valid_to DATE,

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_account_owner_account
        FOREIGN KEY (account_id)
        REFERENCES account(id),

    CONSTRAINT fk_account_owner_customer
        FOREIGN KEY (customer_id)
        REFERENCES customer(id),

    CONSTRAINT ck_account_owner_dates
        CHECK (
            valid_to IS NULL
            OR valid_to >= valid_from
        ),

    CONSTRAINT ck_account_owner_status
        CHECK (
            status IN (
                'ACTIVE',
                'INACTIVE'
            )
        )
);


-- ============================================================
-- 2. ACCOUNT AUTHORIZATION
-- ============================================================

CREATE TABLE account_authorization (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    account_id BIGINT NOT NULL,

    customer_id BIGINT NOT NULL,

    authorization_type VARCHAR(30) NOT NULL,

    valid_from DATE NOT NULL,

    valid_to DATE,

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_account_authorization_account
        FOREIGN KEY (account_id)
        REFERENCES account(id),

    CONSTRAINT fk_account_authorization_customer
        FOREIGN KEY (customer_id)
        REFERENCES customer(id),

    CONSTRAINT ck_account_authorization_type
        CHECK (
            authorization_type IN (
                'POWER_OF_ATTORNEY',
                'LEGAL_GUARDIAN',
                'LEGAL_REPRESENTATIVE',
                'AUTHORIZED_SIGNATORY'
            )
        ),

    CONSTRAINT ck_account_authorization_dates
        CHECK (
            valid_to IS NULL
            OR valid_to >= valid_from
        ),

    CONSTRAINT ck_account_authorization_status
        CHECK (
            status IN (
                'ACTIVE',
                'INACTIVE'
            )
        )
);


-- ============================================================
-- 3. LEGAL ENTITY BOARD MEMBER
-- ============================================================

CREATE TABLE legal_entity_board_member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    legal_entity_customer_id BIGINT NOT NULL,

    customer_id BIGINT NOT NULL,

    position VARCHAR(100) NOT NULL,

    start_date DATE NOT NULL,

    end_date DATE,

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_board_member_legal_entity
        FOREIGN KEY (legal_entity_customer_id)
        REFERENCES customer(id),

    CONSTRAINT fk_board_member_customer
        FOREIGN KEY (customer_id)
        REFERENCES customer(id),

    CONSTRAINT ck_board_member_not_same_customer
        CHECK (
            legal_entity_customer_id <> customer_id
        ),

    CONSTRAINT ck_board_member_position
        CHECK (
            position <> ''
        ),

    CONSTRAINT ck_board_member_dates
        CHECK (
            end_date IS NULL
            OR end_date >= start_date
        ),

    CONSTRAINT ck_board_member_status
        CHECK (
            status IN (
                'ACTIVE',
                'INACTIVE'
            )
        )
);


-- ============================================================
-- 4. LEGAL ENTITY SHAREHOLDER
-- ============================================================

CREATE TABLE legal_entity_shareholder (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    legal_entity_customer_id BIGINT NOT NULL,

    shareholder_customer_id BIGINT NOT NULL,

    ownership_percentage NUMERIC(9,6),

    share_count NUMERIC(20,6),

    start_date DATE NOT NULL,

    end_date DATE,

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_shareholder_legal_entity
        FOREIGN KEY (legal_entity_customer_id)
        REFERENCES customer(id),

    CONSTRAINT fk_shareholder_customer
        FOREIGN KEY (shareholder_customer_id)
        REFERENCES customer(id),

    CONSTRAINT ck_shareholder_not_same_customer
        CHECK (
            legal_entity_customer_id <> shareholder_customer_id
        ),

    CONSTRAINT ck_shareholder_ownership_percentage
        CHECK (
            ownership_percentage IS NULL
            OR (
                ownership_percentage > 0
                AND ownership_percentage <= 100
            )
        ),

    CONSTRAINT ck_shareholder_share_count
        CHECK (
            share_count IS NULL
            OR share_count > 0
        ),

    CONSTRAINT ck_shareholder_dates
        CHECK (
            end_date IS NULL
            OR end_date >= start_date
        ),

    CONSTRAINT ck_shareholder_status
        CHECK (
            status IN (
                'ACTIVE',
                'INACTIVE'
            )
        )
);


