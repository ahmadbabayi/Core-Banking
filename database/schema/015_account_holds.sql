BEGIN;

-- ============================================================
-- 1. ACCOUNT HOLDS
-- A hold reserves funds without changing ledger balance.
-- ============================================================

CREATE TABLE account_hold (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    account_id BIGINT NOT NULL,
    currency_id BIGINT NOT NULL,
    amount NUMERIC NOT NULL,

    reason_code VARCHAR(50) NOT NULL,
    reason_description TEXT,

    reference_type VARCHAR(50),
    reference_id VARCHAR(100),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    effective_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ,

    CONSTRAINT fk_account_hold_account_currency
        FOREIGN KEY (account_id, currency_id)
        REFERENCES account(id, currency_id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_account_hold_amount
        CHECK (amount > 0),

    CONSTRAINT ck_account_hold_reason
        CHECK (BTRIM(reason_code) <> ''),

    CONSTRAINT ck_account_hold_expiry
        CHECK (expires_at IS NULL OR expires_at > effective_at)
);

CREATE INDEX ix_account_hold_account
    ON account_hold (account_id);

CREATE INDEX ix_account_hold_reference
    ON account_hold (reference_type, reference_id)
    WHERE reference_type IS NOT NULL
      AND reference_id IS NOT NULL;


-- ============================================================
-- 2. APPEND-ONLY HOLD EVENTS
-- Idempotency is scoped to each hold.
-- ============================================================

CREATE TABLE account_hold_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    hold_id BIGINT NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,

    event_type VARCHAR(30) NOT NULL,
    amount NUMERIC NOT NULL,

    effective_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    reference_type VARCHAR(50),
    reference_id VARCHAR(100),
    reason_code VARCHAR(50) NOT NULL,

    CONSTRAINT fk_account_hold_event_hold
        FOREIGN KEY (hold_id)
        REFERENCES account_hold(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_account_hold_event_idempotency
        UNIQUE (hold_id, idempotency_key),

    CONSTRAINT ck_account_hold_event_idempotency_key
        CHECK (BTRIM(idempotency_key) <> ''),

    CONSTRAINT ck_account_hold_event_type
        CHECK (
            event_type IN (
                'PARTIAL_RELEASE',
                'FULL_RELEASE',
                'EXPIRY_RELEASE',
                'CANCELLATION_RELEASE'
            )
        ),

    CONSTRAINT ck_account_hold_event_amount
        CHECK (amount > 0),

    CONSTRAINT ck_account_hold_event_reason
        CHECK (BTRIM(reason_code) <> '')
);

CREATE INDEX ix_account_hold_events_hold
    ON account_hold_events (hold_id, id);


-- ============================================================
-- 3. VALIDATE RELEASE EVENTS AND HANDLE IDEMPOTENCY
-- Locking the hold serializes release attempts for that hold.
-- A repeated identical request does not create another event.
-- Reusing a key with a different payload is rejected.
-- ============================================================

CREATE FUNCTION validate_account_hold_event()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_hold account_hold%ROWTYPE;
    v_existing account_hold_events%ROWTYPE;
    v_released NUMERIC;
    v_remaining NUMERIC;
    v_now TIMESTAMPTZ;
BEGIN
    v_now := clock_timestamp();

    SELECT *
      INTO v_hold
      FROM account_hold
     WHERE id = NEW.hold_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'ACCOUNT_HOLD_NOT_FOUND'
            USING ERRCODE = '23503';
    END IF;

    -- Check the idempotency key before applying release validation.
    -- This permits a retry even if the original event fully released
    -- the hold.
    SELECT *
      INTO v_existing
      FROM account_hold_events
     WHERE hold_id = NEW.hold_id
       AND idempotency_key = NEW.idempotency_key;

    IF FOUND THEN
        IF v_existing.event_type = NEW.event_type
           AND v_existing.amount = NEW.amount
           AND v_existing.effective_at = NEW.effective_at
           AND v_existing.reference_type
               IS NOT DISTINCT FROM NEW.reference_type
           AND v_existing.reference_id
               IS NOT DISTINCT FROM NEW.reference_id
           AND v_existing.reason_code = NEW.reason_code
        THEN
            -- Exact retry: do not insert a duplicate event.
            RETURN NULL;
        END IF;

        RAISE EXCEPTION 'ACCOUNT_HOLD_IDEMPOTENCY_KEY_REUSED'
            USING ERRCODE = '23505';
    END IF;

    IF NEW.effective_at > v_now THEN
        RAISE EXCEPTION 'ACCOUNT_HOLD_EVENT_CANNOT_BE_FUTURE_DATED'
            USING ERRCODE = '23514';
    END IF;

    IF v_now < v_hold.effective_at THEN
        RAISE EXCEPTION 'ACCOUNT_HOLD_NOT_YET_EFFECTIVE'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.effective_at < v_hold.effective_at THEN
        RAISE EXCEPTION 'ACCOUNT_HOLD_EVENT_BEFORE_EFFECTIVE_TIME'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.event_type = 'EXPIRY_RELEASE' THEN
        IF v_hold.expires_at IS NULL
           OR v_now < v_hold.expires_at THEN
            RAISE EXCEPTION 'ACCOUNT_HOLD_NOT_EXPIRED'
                USING ERRCODE = '23514';
        END IF;
    ELSE
        IF v_hold.expires_at IS NOT NULL
           AND v_now >= v_hold.expires_at THEN
            RAISE EXCEPTION 'EXPIRED_HOLD_REQUIRES_EXPIRY_RELEASE'
                USING ERRCODE = '23514';
        END IF;
    END IF;

    SELECT COALESCE(SUM(amount), 0)
      INTO v_released
      FROM account_hold_events
     WHERE hold_id = NEW.hold_id;

    v_remaining := v_hold.amount - v_released;

    IF v_remaining <= 0 THEN
        RAISE EXCEPTION 'ACCOUNT_HOLD_ALREADY_FULLY_RELEASED'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.amount > v_remaining THEN
        RAISE EXCEPTION 'ACCOUNT_HOLD_RELEASE_EXCEEDS_REMAINING_AMOUNT'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.event_type = 'PARTIAL_RELEASE'
       AND NEW.amount >= v_remaining THEN
        RAISE EXCEPTION 'PARTIAL_RELEASE_MUST_BE_LESS_THAN_REMAINING_AMOUNT'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.event_type IN (
        'FULL_RELEASE',
        'EXPIRY_RELEASE',
        'CANCELLATION_RELEASE'
    ) AND NEW.amount <> v_remaining THEN
        RAISE EXCEPTION 'FULL_RELEASE_MUST_MATCH_REMAINING_AMOUNT'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_account_hold_event
BEFORE INSERT ON account_hold_events
FOR EACH ROW
EXECUTE FUNCTION validate_account_hold_event();


-- ============================================================
-- 4. PROTECT HOLD DETAILS
-- ============================================================

CREATE FUNCTION protect_account_hold()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'ACCOUNT_HOLD_IS_IMMUTABLE'
        USING ERRCODE = '23514';
END;
$$;

CREATE TRIGGER trg_protect_account_hold
BEFORE UPDATE OR DELETE ON account_hold
FOR EACH ROW
EXECUTE FUNCTION protect_account_hold();


-- ============================================================
-- 5. PROTECT EVENT HISTORY
-- ============================================================

CREATE FUNCTION prevent_account_hold_event_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'ACCOUNT_HOLD_EVENTS_ARE_IMMUTABLE'
        USING ERRCODE = '23514';
END;
$$;

CREATE TRIGGER trg_account_hold_event_immutable
BEFORE UPDATE OR DELETE ON account_hold_events
FOR EACH ROW
EXECUTE FUNCTION prevent_account_hold_event_mutation();


-- ============================================================
-- 6. DERIVED HOLD STATUS
-- Expired holds stop blocking funds based on time,
-- regardless of whether an EXPIRY_RELEASE event exists.
-- ============================================================

CREATE VIEW account_hold_status AS
WITH release_totals AS (
    SELECT
        h.id AS hold_id,
        COALESCE(SUM(e.amount), 0) AS released_amount,
        COUNT(e.id) AS release_event_count,
        (
            ARRAY_AGG(e.event_type ORDER BY e.id DESC)
            FILTER (WHERE e.id IS NOT NULL)
        )[1] AS last_release_event_type
    FROM account_hold h
    LEFT JOIN account_hold_events e
        ON e.hold_id = h.id
    GROUP BY h.id
),
hold_amounts AS (
    SELECT
        h.id AS hold_id,
        h.account_id,
        h.currency_id,
        h.amount AS original_amount,
        h.amount - r.released_amount AS remaining_amount,
        h.reason_code,
        h.reason_description,
        h.reference_type,
        h.reference_id,
        h.created_at,
        h.effective_at,
        h.expires_at,
        r.release_event_count,
        r.last_release_event_type
    FROM account_hold h
    JOIN release_totals r
        ON r.hold_id = h.id
)
SELECT
    hold_id,
    account_id,
    currency_id,
    original_amount,
    remaining_amount,
    reason_code,
    reason_description,
    reference_type,
    reference_id,
    created_at,
    effective_at,
    expires_at,
    release_event_count,
    last_release_event_type,
    CASE
        WHEN remaining_amount = 0
             AND last_release_event_type = 'EXPIRY_RELEASE'
            THEN 'EXPIRED'

        WHEN remaining_amount = 0
             AND last_release_event_type = 'CANCELLATION_RELEASE'
            THEN 'CANCELLED'

        WHEN remaining_amount = 0
            THEN 'RELEASED'

        WHEN effective_at > CURRENT_TIMESTAMP
            THEN 'SCHEDULED'

        WHEN expires_at IS NOT NULL
             AND expires_at <= CURRENT_TIMESTAMP
            THEN 'EXPIRED'

        WHEN remaining_amount < original_amount
            THEN 'PARTIALLY_RELEASED'

        ELSE 'ACTIVE'
    END AS status,
    CASE
        WHEN effective_at > CURRENT_TIMESTAMP
            THEN 0::NUMERIC

        WHEN expires_at IS NOT NULL
             AND expires_at <= CURRENT_TIMESTAMP
            THEN 0::NUMERIC

        ELSE GREATEST(remaining_amount, 0)
    END AS currently_blocked_amount
FROM hold_amounts;

COMMIT;
