BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ============================================================
-- 1. PRODUCT BALANCE RULE
-- Effective intervals use [effective_from, effective_to).
-- ============================================================

CREATE TABLE product_balance_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL,

    minimum_balance NUMERIC NOT NULL DEFAULT 0,
    overdraft_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    overdraft_limit NUMERIC NOT NULL DEFAULT 0,

    effective_from TIMESTAMPTZ NOT NULL,
    effective_to TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_product_balance_rule_product
        FOREIGN KEY (product_id)
        REFERENCES product(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_product_balance_rule_minimum
        CHECK (minimum_balance >= 0),

    CONSTRAINT ck_product_balance_rule_overdraft_limit
        CHECK (overdraft_limit >= 0),

    CONSTRAINT ck_product_balance_rule_overdraft_disabled
        CHECK (
            overdraft_enabled
            OR overdraft_limit = 0
        ),

    CONSTRAINT ck_product_balance_rule_effective_dates
        CHECK (
            effective_to IS NULL
            OR effective_to > effective_from
        ),

    CONSTRAINT ex_product_balance_rule_period
        EXCLUDE USING gist (
            product_id WITH =,
            tstzrange(
                effective_from,
                effective_to,
                '[)'
            ) WITH &&
        )
);

CREATE INDEX ix_product_balance_rule_lookup
    ON product_balance_rule (
        product_id,
        effective_from DESC
    );

-- ============================================================
-- 2. ACCOUNT BALANCE RULE OVERRIDE
-- NULL means inherit the corresponding product setting.
-- Minimum balance can be overridden independently.
-- Overdraft enabled/limit must be overridden together.
-- ============================================================

CREATE TABLE account_balance_rule_override (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    account_id BIGINT NOT NULL,

    minimum_balance NUMERIC,
    overdraft_enabled BOOLEAN,
    overdraft_limit NUMERIC,

    effective_from TIMESTAMPTZ NOT NULL,
    effective_to TIMESTAMPTZ,

    reason_code VARCHAR(50) NOT NULL,
    reference_number VARCHAR(100),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_account_balance_rule_override_account
        FOREIGN KEY (account_id)
        REFERENCES account(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_account_balance_override_has_setting
        CHECK (
            minimum_balance IS NOT NULL
            OR overdraft_enabled IS NOT NULL
        ),

    CONSTRAINT ck_account_balance_override_minimum
        CHECK (
            minimum_balance IS NULL
            OR minimum_balance >= 0
        ),

    CONSTRAINT ck_account_balance_override_limit
        CHECK (
            overdraft_limit IS NULL
            OR overdraft_limit >= 0
        ),

    CONSTRAINT ck_account_balance_override_overdraft_pair
        CHECK (
            (overdraft_enabled IS NULL)
            =
            (overdraft_limit IS NULL)
        ),

    CONSTRAINT ck_account_balance_override_disabled
        CHECK (
            overdraft_enabled IS DISTINCT FROM FALSE
            OR overdraft_limit = 0
        ),

    CONSTRAINT ck_account_balance_override_reason
        CHECK (BTRIM(reason_code) <> ''),

    CONSTRAINT ck_account_balance_override_effective_dates
        CHECK (
            effective_to IS NULL
            OR effective_to > effective_from
        )
);

-- A given setting cannot have overlapping effective intervals.
-- Minimum balance is independent from the overdraft pair.

ALTER TABLE account_balance_rule_override
    ADD CONSTRAINT ex_account_balance_override_minimum_period
    EXCLUDE USING gist (
        account_id WITH =,
        tstzrange(
            effective_from,
            effective_to,
            '[)'
        ) WITH &&
    )
    WHERE (minimum_balance IS NOT NULL);

ALTER TABLE account_balance_rule_override
    ADD CONSTRAINT ex_account_balance_override_overdraft_period
    EXCLUDE USING gist (
        account_id WITH =,
        tstzrange(
            effective_from,
            effective_to,
            '[)'
        ) WITH &&
    )
    WHERE (overdraft_enabled IS NOT NULL);

CREATE INDEX ix_account_balance_override_lookup
    ON account_balance_rule_override (
        account_id,
        effective_from DESC
    );

COMMIT;
