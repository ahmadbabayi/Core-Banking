-- ============================================================
-- Schema 012: Product Ledger Mapping
-- PostgreSQL
--
-- One product may have one ledger mapping at any given date.
-- Historical mappings are retained.
-- Accounts reference the exact mapping used at opening.
-- ============================================================

BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ------------------------------------------------------------
-- 1. Product-to-ledger mapping
-- ------------------------------------------------------------

CREATE TABLE product_ledger_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL,
    account_type_id BIGINT NOT NULL,
    currency_id BIGINT NOT NULL,
    ledger_account_id BIGINT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    effective_from DATE NOT NULL,
    effective_to DATE,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_plm_product_type_currency
        FOREIGN KEY (product_id, account_type_id, currency_id)
        REFERENCES product (id, account_type_id, currency_id),

    CONSTRAINT fk_plm_ledger_currency
        FOREIGN KEY (ledger_account_id, currency_id)
        REFERENCES ledger_account (id, currency_id),

    CONSTRAINT ck_plm_status
        CHECK (status IN ('ACTIVE', 'INACTIVE')),

    -- effective_to is exclusive.
    CONSTRAINT ck_plm_effective_dates
        CHECK (
            effective_to IS NULL
            OR effective_to > effective_from
        ),

    -- Referenced by the account composite foreign key.
    CONSTRAINT uq_plm_account_reference
        UNIQUE (
            id,
            product_id,
            account_type_id,
            currency_id,
            ledger_account_id
        )
);

-- Do not allow overlapping validity periods for the same
-- product, including periods belonging to inactive mappings.
-- An old period must be closed before a new one is created.
ALTER TABLE product_ledger_mapping
    ADD CONSTRAINT ex_plm_product_periods
    EXCLUDE USING gist (
        product_id WITH =,
        daterange(effective_from, effective_to, '[)') WITH &&
    );

CREATE INDEX idx_plm_product
    ON product_ledger_mapping (product_id);

CREATE INDEX idx_plm_ledger_account
    ON product_ledger_mapping (ledger_account_id);

-- ------------------------------------------------------------
-- 2. Validate existing account history before migration
-- ------------------------------------------------------------

-- This migration must not guess historical ledger assignments
-- when a product has used multiple ledger accounts.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM account
        GROUP BY product_id
        HAVING COUNT(DISTINCT ledger_account_id) > 1
    ) THEN
        RAISE EXCEPTION
            'Migration 012 aborted: a product has accounts assigned '
            'to multiple ledger accounts. Historical mappings '
            'must be reviewed before migration.';
    END IF;
END;
$$;

-- Backfill mappings for products that already have accounts.
-- Current account data is used only as the source of the ledger
-- assignment; products without accounts need configured mappings.
INSERT INTO product_ledger_mapping (
    product_id,
    account_type_id,
    currency_id,
    ledger_account_id,
    status,
    effective_from,
    effective_to
)
SELECT DISTINCT
    p.id,
    p.account_type_id,
    p.currency_id,
    a.ledger_account_id,
    p.status,
    p.effective_from,
    p.effective_to
FROM account AS a
JOIN product AS p
  ON p.id = a.product_id
 AND p.account_type_id = a.account_type_id
 AND p.currency_id = a.currency_id;

-- ------------------------------------------------------------
-- 3. Link every account to its exact mapping
-- ------------------------------------------------------------

ALTER TABLE account
    ADD COLUMN product_ledger_mapping_id BIGINT;

UPDATE account AS a
SET product_ledger_mapping_id = plm.id
FROM product_ledger_mapping AS plm
WHERE plm.product_id = a.product_id
  AND plm.account_type_id = a.account_type_id
  AND plm.currency_id = a.currency_id
  AND plm.ledger_account_id = a.ledger_account_id;

-- Existing accounts must have a corresponding mapping.
ALTER TABLE account
    ALTER COLUMN product_ledger_mapping_id SET NOT NULL;

ALTER TABLE account
    ADD CONSTRAINT fk_account_product_ledger_mapping
    FOREIGN KEY (
        product_ledger_mapping_id,
        product_id,
        account_type_id,
        currency_id,
        ledger_account_id
    )
    REFERENCES product_ledger_mapping (
        id,
        product_id,
        account_type_id,
        currency_id,
        ledger_account_id
    );

CREATE INDEX idx_account_product_ledger_mapping
    ON account (product_ledger_mapping_id);

COMMIT;
